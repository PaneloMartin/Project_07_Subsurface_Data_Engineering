"""Offline SQL/transaction tests. SQLite executes previews and predicates;
MERGE is simulated because SQLite does not implement Snowflake MERGE.
No Snowflake connection or Docker service is used.
"""
import importlib.util
from pathlib import Path
import re
import sqlite3
import sys
import types
import unittest
from unittest.mock import patch

# Import without requiring the Snowflake driver or reading credentials.
connector = types.ModuleType('snowflake.connector')
snowflake = types.ModuleType('snowflake')
snowflake.connector = connector
spec = importlib.util.spec_from_file_location(
    'loader', Path(__file__).resolve().parents[1] / 'ingestion/load_snowflake.py')
loader = importlib.util.module_from_spec(spec)
with patch.dict(sys.modules, {'snowflake': snowflake, 'snowflake.connector': connector}):
    spec.loader.exec_module(loader)


class LocalConnection:
    def __init__(self):
        self.db = sqlite3.connect(':memory:')
        self.db.create_function('REGEXP_REPLACE', 3, lambda v, p, r:
                                None if v is None else re.sub(r'\s+', r, v))
        self.statements = []
        self.fail_begin_reply = False
        self.fail_merge = None
        self.fail_commit = False
        self.fail_rollback = False
        self.rollbacks = 0
        self.commits = 0
        for table, columns in loader.TABLE_COLUMNS.items():
            for name in (table, 'STG_' + table):
                self.db.execute(f"CREATE TABLE {name} ({', '.join(columns)})")
        self.db.commit()

    def seed(self, table, row, staging=False):
        name = ('STG_' if staging else '') + table
        cols = loader.TABLE_COLUMNS[table]
        self.db.execute(f"INSERT INTO {name} VALUES ({','.join('?' for _ in cols)})",
                        [row.get(c) for c in cols])
        self.db.commit()

    def cursor(self):
        return LocalCursor(self)

    def commit(self):
        self.statements.append('COMMIT')
        self.commits += 1
        if self.fail_commit:
            raise RuntimeError('commit failed')
        self.db.commit()

    def rollback(self):
        self.statements.append('ROLLBACK')
        self.rollbacks += 1
        self.db.rollback()
        if self.fail_rollback:
            raise RuntimeError('rollback failed')


class LocalCursor:
    def __init__(self, connection):
        self.connection = connection
        self.result = None
        self.description = None

    def execute(self, sql):
        c = self.connection
        c.statements.append(sql)
        sql = sql.replace('SUBSURFACE_DB.RAW.', '')
        if sql == 'BEGIN TRANSACTION':
            c.db.execute(sql)
            if c.fail_begin_reply:
                raise RuntimeError('begin response lost')
        elif sql.startswith('MERGE'):
            table = sql.split()[2]
            if c.fail_merge == table:
                raise RuntimeError('merge failed')
            # Execute the exact ON/WHEN predicate and assignments generated by production.
            match = re.fullmatch(
                r'MERGE INTO (\w+) r USING (\w+) s ON (.*?) WHEN MATCHED AND \((.*?)\) '
                r'THEN UPDATE SET (.*?) WHEN NOT MATCHED THEN INSERT \((.*?)\) VALUES \((.*?)\)', sql)
            if not match:
                raise AssertionError(sql)
            _, staging, join, changed, assignments, columns, values = match.groups()
            updates = c.db.execute(f'SELECT COUNT(*) FROM {table} r JOIN {staging} s '
                                   f'ON {join} WHERE {changed}').fetchone()[0]
            c.db.execute(f'UPDATE {table} AS r SET {assignments} FROM {staging} s '
                         f'WHERE {join} AND ({changed})')
            inserts = c.db.execute(f'SELECT COUNT(*) FROM {staging} s WHERE NOT EXISTS '
                                   f'(SELECT 1 FROM {table} r WHERE {join})').fetchone()[0]
            c.db.execute(f'INSERT INTO {table} ({columns}) SELECT {values} FROM {staging} s '
                         f'WHERE NOT EXISTS (SELECT 1 FROM {table} r WHERE {join})')
            self.result = (inserts, updates)
            self.description = [('number of rows inserted',), ('number of rows updated',)]
        else:
            self.result = c.db.execute(sql).fetchone()
        return self

    def fetchone(self):
        return self.result

    def close(self):
        pass


class PublicationTests(unittest.TestCase):
    def setUp(self):
        self.c = LocalConnection()

    def test_insert_all_tables_and_idempotence(self):
        for table, keys in loader.BUSINESS_KEYS.items():
            self.c.seed(table, dict.fromkeys(keys, 'key'), staging=True)
        preview = loader.publish_to_raw(self.c)
        self.assertTrue(all(r == {'inserted': 1, 'updated': 0} for r in preview.values()))
        self.assertFalse(any(s.startswith(('BEGIN', 'MERGE')) for s in self.c.statements))
        self.assertEqual(loader.publish_to_raw(self.c, False), preview)
        again = loader.publish_to_raw(self.c, False)
        self.assertTrue(all(r == {'inserted': 0, 'updated': 0} for r in again.values()))
        self.assertEqual(self.c.commits, 2)

    def test_updates_null_transitions_and_null_retention(self):
        for old, new, expected in [(None, None, 0), (None, 2, 1), (2, None, 1), (2, 3, 1), (2, 2, 0)]:
            with self.subTest(old=old, new=new):
                c = LocalConnection()
                row = {'FILE_ID': 'f', 'DEPTH': 1, 'MNEMONIC': 'GR', 'VALUE': old}
                c.seed('MEASUREMENTS', row)
                c.seed('MEASUREMENTS', dict(row, VALUE=new), True)
                self.assertEqual(loader.publish_to_raw(c)['MEASUREMENTS']['updated'], expected)
                self.assertEqual(loader.publish_to_raw(c, False)['MEASUREMENTS']['updated'], expected)
                self.assertEqual(c.db.execute('SELECT VALUE FROM MEASUREMENTS').fetchone()[0], new)

    def test_location_spaces_and_original_values(self):
        self.c.seed('WELLS', {'KGS_ID': 'k', 'LOCATION': ' A  B ', 'API': 'old'})
        self.c.seed('WELLS', {'KGS_ID': 'k', 'LOCATION': '\tA B\n', 'API': 'old'}, True)
        self.assertEqual(loader.publish_to_raw(self.c, False)['WELLS']['updated'], 0)
        self.assertEqual(self.c.db.execute('SELECT LOCATION FROM WELLS').fetchone()[0], ' A  B ')
        self.c.db.execute("UPDATE STG_WELLS SET API='new'")
        self.c.db.commit()
        self.assertEqual(loader.publish_to_raw(self.c, False)['WELLS']['updated'], 1)
        self.assertEqual(self.c.db.execute('SELECT LOCATION FROM WELLS').fetchone()[0], '\tA B\n')
        self.c.db.execute("UPDATE STG_WELLS SET LOCATION=' C '")
        self.c.db.commit()
        self.assertEqual(loader.publish_to_raw(self.c, False)['WELLS']['updated'], 1)

    def test_invalid_keys_every_table_and_side(self):
        for table, keys in loader.BUSINESS_KEYS.items():
            for staging in (True, False):
                for invalid in ('null', 'duplicate'):
                    for key in keys:
                        with self.subTest(table=table, staging=staging, invalid=invalid, key=key):
                            c = LocalConnection()
                            row = dict.fromkeys(keys, 'k')
                            if invalid == 'null':
                                row[key] = None
                            c.seed(table, row, staging)
                            if invalid == 'duplicate':
                                c.seed(table, row, staging)
                            with self.assertRaises(ValueError):
                                loader.publish_to_raw(c, False)
                            self.assertEqual(c.rollbacks, 1)
                            self.assertFalse(any(s.startswith('MERGE') for s in c.statements))

    def test_merge_and_commit_failures_rollback_all_tables(self):
        for failure in (*loader.FILES, 'commit'):
            with self.subTest(failure=failure):
                c = LocalConnection()
                for table, keys in loader.BUSINESS_KEYS.items():
                    c.seed(table, dict.fromkeys(keys, 'k'), True)
                c.fail_merge = failure
                c.fail_commit = failure == 'commit'
                with self.assertRaises(RuntimeError):
                    loader.publish_to_raw(c, False)
                self.assertEqual(c.rollbacks, 1)
                for table in loader.FILES:
                    self.assertEqual(c.db.execute(f'SELECT COUNT(*) FROM {table}').fetchone()[0], 0)

    def test_rollback_error_keeps_original_exception(self):
        self.c.fail_merge = 'WELLS'
        self.c.fail_rollback = True
        with self.assertRaisesRegex(RuntimeError, 'merge failed'):
            loader.publish_to_raw(self.c, False)

    def test_begin_response_failure_attempts_rollback(self):
        self.c.fail_begin_reply = True
        with self.assertRaisesRegex(RuntimeError, 'begin response lost'):
            loader.publish_to_raw(self.c, False)
        self.assertEqual(self.c.rollbacks, 1)
        self.assertFalse(self.c.db.in_transaction)
        self.assertFalse(any(s.startswith('MERGE') for s in self.c.statements))

    def test_transaction_boundaries_and_preflight_order(self):
        loader.publish_to_raw(self.c, False)
        statements = self.c.statements
        self.assertEqual(statements[0], 'BEGIN TRANSACTION')
        self.assertEqual(statements[-1], 'COMMIT')
        self.assertEqual(statements.count('BEGIN TRANSACTION'), 1)
        self.assertEqual(statements.count('COMMIT'), 1)
        merges = [i for i, sql in enumerate(statements) if sql.startswith('MERGE')]
        self.assertEqual(len(merges), 4)
        for sql in statements[1:-1]:
            self.assertIn(sql.split()[0], ('SELECT', 'MERGE'))
        for table in loader.FILES:
            for source in (f'STG_{table}', f'SUBSURFACE_DB.RAW.{table}'):
                checks = [i for i, sql in enumerate(statements)
                          if f'FROM {source} WHERE ' in sql
                          or f'FROM {source} GROUP BY ' in sql]
                self.assertEqual(len(checks), 2)
                self.assertLess(max(checks), min(merges))

    def test_cli_defaults_and_explicit_modes(self):
        for argv, dry in [([], True), (['--dry-run'], True), (['--publish'], False)]:
            with self.subTest(argv=argv), patch.object(loader, 'connect_to_snowflake') as connect:
                with patch.multiple(loader, **{name: unittest.mock.DEFAULT for name in (
                    'validate_local_files', 'inspect_snowflake', 'upload_csv_files',
                    'load_into_staging', 'validate_staging', 'validate_staging_keys',
                    'compare_staging_to_raw', 'diagnose_wells', 'preview_merge', 'publish_to_raw')}) as mocks:
                    loader.main(argv)
                    mocks['publish_to_raw'].assert_called_once_with(connect.return_value, dry_run=dry)
        with self.assertRaises(SystemExit):
            loader.main(['--publish', '--dry-run'])


if __name__ == '__main__':
    unittest.main()
